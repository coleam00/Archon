/**
 * Regenerate `policy-texts.generated.ts` from the policy documents in `policy/`:
 * `bun .archon/workflows/sdlc/.shared/policy-sync.ts`. The documents stay the source of truth;
 * the generated module is what a run's capture carries (it keeps only `.ts`, `.js` and `.py` from
 * `.shared/`), and `.archon/scripts/__tests__/policy-texts.test.ts` fails when the two disagree.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dir, 'policy');

export function policyTextsSource(): string {
  const entries = readdirSync(dir)
    .filter(name => name.endsWith('.md'))
    .sort()
    .map(name => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(dir, name), 'utf8').replace(/\r\n/g, '\n'))},`);
  return [
    '// Generated by policy-sync.ts from .shared/policy/*.md; do not edit by hand.',
    '',
    'export const POLICY_TEXTS: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

if (import.meta.main) {
  writeFileSync(join(import.meta.dir, 'policy-texts.generated.ts'), policyTextsSource());
}
