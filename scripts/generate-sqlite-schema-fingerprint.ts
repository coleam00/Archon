import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..');
const directory = join(root, 'packages/core/src/db/adapters');
const hash = createHash('sha256');
for (const name of ['sqlite.ts', 'sqlite-migrations.ts', 'sqlite-schema-state.ts']) {
  hash
    .update(name)
    .update('\0')
    .update(readFileSync(join(directory, name), 'utf8').replaceAll('\r\n', '\n'))
    .update('\0');
}
const output = `// Generated by scripts/generate-sqlite-schema-fingerprint.ts.\nexport const SQLITE_SCHEMA_DIGEST = '${hash.digest('hex')}';\n`;
const target = join(directory, 'sqlite-schema-fingerprint.generated.ts');
if (process.argv.includes('--check')) {
  if (!Bun.file(target).size || readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) {
    console.error(
      'SQLite schema fingerprint is stale. Run bun run generate:sqlite-schema-fingerprint'
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
