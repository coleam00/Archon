#!/usr/bin/env bun
/**
 * Regenerates packages/script-api/src/archon-script.d.ts, the declaration of
 * the `archon:script` module a workflow script imports.
 *
 * Two owners feed it. The contract types come from the schemas the host validates with:
 * the forge operations (`@archon/forge`) and the engine's state, node-outcome and start
 * shapes (`@archon/workflows`). The signatures come from the module's own source,
 * script-api/module.ts, through TypeScript's declaration emit. The engine embeds the
 * result as text, so `archon script types` can write it from a compiled binary, which
 * carries neither TypeScript nor this source.
 *
 * Usage:
 *   bun run scripts/generate-script-api-types.ts          # write
 *   bun run scripts/generate-script-api-types.ts --check  # exit 1 when stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import ts from 'typescript';
import { cliForgeJsonSchemas } from '../packages/forge/src/cli-json-schemas';
import {
  convertOutputSchema,
  indent,
  quote,
} from '../packages/workflows/src/output-types/schema-to-ts';
import { scriptContractTypes } from '../packages/workflows/src/script-api/contract-schemas';

const DIR = resolve(import.meta.dir, '../packages/script-api/src');
const MODULE = resolve(DIR, 'module.ts');
const OUT = resolve(DIR, 'archon-script.d.ts');

function typeOf(what: string, schema: unknown): string {
  try {
    return convertOutputSchema(schema).type;
  } catch (error) {
    throw new Error(`The schema of ${what} cannot be stated as a type`, { cause: error });
  }
}

function contractTypes(): string {
  const forge = cliForgeJsonSchemas();
  const operations = forge.operations.map(({ op, request, result }) => {
    const fields = `readonly request: ${typeOf(`${op}'s request`, request)};\nreadonly result: ${typeOf(`${op}'s result`, result)};`;
    return `${quote(op)}: {\n${indent(fields)}\n};`;
  });
  return [
    `/** Every forge operation: the request it takes and the result it returns. */\nexport interface ForgeOperations {\n${indent(operations.join('\n'))}\n}`,
    `/** A failed forge operation: the typed reason and, for a write, what is known of its outcome. */\nexport type ForgeFailure = ${typeOf('a failed forge answer', forge.failure)};`,
    ...scriptContractTypes().map(
      ({ name, doc, schema }) => `/** ${doc} */\nexport type ${name} = ${typeOf(name, schema)};`
    ),
  ].join('\n\n');
}

/** The module's exported signatures, as they read inside a `declare module` block. */
function moduleSignatures(): string {
  const emitted = ts.transpileDeclaration(readFileSync(MODULE, 'utf8'), {
    fileName: MODULE,
    reportDiagnostics: true,
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  });
  if (emitted.diagnostics?.length) {
    const first = emitted.diagnostics[0];
    throw new Error(
      `module.ts needs an explicit type to state its declaration: ${ts.flattenDiagnosticMessageText(first?.messageText ?? '', '\n')}`
    );
  }
  const file = ts.createSourceFile('module.d.ts', emitted.outputText, ts.ScriptTarget.ES2022);
  return file.statements
    .filter(statement => !ts.isImportDeclaration(statement) && !ts.isExportDeclaration(statement))
    .map(statement =>
      statement
        .getFullText(file)
        .trim()
        .replace(/^(export )?declare /m, '$1')
    )
    .join('\n');
}

const content = `// Generated by \`bun run generate:script-api-types\` from the forge and engine schemas and
// from packages/script-api/src/module.ts. Do not edit.

declare module 'archon:script' {
${indent(contractTypes())}

${indent(moduleSignatures())}
}
`;

let existing = '';
try {
  existing = readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n');
} catch (error) {
  if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
}
if (existing === content) {
  console.log(`Up to date: ${OUT}`);
} else if (process.argv.includes('--check')) {
  console.error(`${OUT} is stale. Run 'bun run generate:script-api-types' and commit the result.`);
  process.exit(1);
} else {
  writeFileSync(OUT, content);
  console.log(`Wrote ${OUT}`);
}
